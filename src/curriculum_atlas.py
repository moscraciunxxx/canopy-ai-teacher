def _node(
    node_id: str,
    short: str,
    label: str,
    icon: str,
    color: str,
    model: str,
    question: str,
    description: str,
    hint: str,
    test: str,
) -> dict[str, Any]:
    """Build one render-ready learning node with a progressive explanation."""

    return {
        "id": node_id,
        "short": short,
        "label": label,
        "icon": icon,
        "color": color,
        "mastery": 0.0,
        "equation": model,
        "question": question,
        "description": description,
        "hint": hint,
        "explain_steps": (
            ("Notice the structure", model, description),
            ("Name the evidence", question, hint),
            ("Stress-test the model", test, "Change one assumption and predict what evidence should move if the model is useful."),
        ),
    }


def _practice(
    item_id: str,
    title: str,
    model: str,
    question: str,
    answer: str,
    terms: tuple[str, ...],
    skill: str,
    transfer: str,
    explanation: str,
    difficulty: int,
) -> dict[str, Any]:
    return {
        "id": item_id,
        "title": title,
        "equation": model,
        "question": question,
        "answer": answer,
        "answer_type": "text",
        "accepted_answers": [answer],
        "required_terms": list(terms),
        "skill": skill,
        "transfer": transfer,
        "hint_ladder": [
            "Name the most important relationship before giving a conclusion.",
            "Point to one piece of evidence in the model or source.",
            "Explain what would change your mind or alter the prediction.",
        ],
        "difficulty": difficulty,
        "explanation": explanation,
    }


