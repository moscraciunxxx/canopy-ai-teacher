def get_academies() -> list[Academy]:
    """Return independent academy records in display order."""

    return copy.deepcopy(list(_ACADEMIES))


def get_courses(academy: AcademyId | str | None = None) -> list[Course]:
    """Return independent courses, optionally filtered by academy."""

    if academy is None:
        return copy.deepcopy(list(_COURSES))
    normalized = str(academy).strip().lower()
    return copy.deepcopy([course for course in _COURSES if course["academy"] == normalized])


def get_course(course_id: str) -> Course:
    """Return one course by stable id."""

    for course in _COURSES:
        if course["id"] == course_id:
            return copy.deepcopy(course)
    raise KeyError(f"Unknown course: {course_id}")


def default_course_id(academy: AcademyId | str = "stem") -> str:
    """Return a compelling default course for an academy."""

    normalized = str(academy).strip().lower()
    return "physics-flight" if normalized == "stem" else "history-sources"


def course_nodes(course: Mapping[str, Any]) -> tuple[dict[str, Any], ...]:
    """Return a fresh tuple of path nodes for app rendering."""

    return tuple(copy.deepcopy(list(course.get("path", []))))


def course_practice(course: Mapping[str, Any]) -> tuple[dict[str, Any], ...]:
    """Return a fresh tuple of practice missions for app rendering."""

    return tuple(copy.deepcopy(list(course.get("practice", []))))


